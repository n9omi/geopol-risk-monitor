"""Step 7: makes the site standalone and documents the data.
- site/data/manifest.json: every dataset with title, description, row count, date coverage and size
- site/index.html: the page fragment wrapped in a full HTML document with the runtime and theme
- docs/data_inventory.md and docs/sources.md: generated tables of datasets and of every cited source
"""
import os, sys, json, re, datetime as dt
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from paths import OUT, SITE, TEMPLATES, ROOT

META = {m['id']: m for m in json.load(open(os.path.join(TEMPLATES, 'dataset_meta.json')))}
DATE_KEYS = ('date', 'as_of', 'last_action', 'next_date', 'key_date')

def coverage(rows):
    ds = []
    for r in rows if isinstance(rows, list) else [rows]:
        for k in DATE_KEYS:
            v = r.get(k) if isinstance(r, dict) else None
            if isinstance(v, str) and re.match(r'^\d{4}-\d{2}-\d{2}', v):
                ds.append(v[:10])
    return (min(ds), max(ds)) if ds else (None, None)

datasets = []
for f in sorted(os.listdir(OUT)):
    if not f.endswith('.json') or f == 'manifest.json':
        continue
    did = f[:-5]
    rows = json.load(open(OUT + f))
    lo, hi = coverage(rows)
    m = META.get(did, {'title': did, 'description': ''})
    desc = m['description'].replace("Claude's judgment", 'analyst judgment').replace('(Claude’s judgment)', '(analyst judgment)')
    datasets.append({'id': did, 'file': f, 'title': m['title'], 'description': desc, 'rows': len(rows) if isinstance(rows, list) else 1,
                     'from': lo, 'to': hi, 'bytes': os.path.getsize(OUT + f)})
json.dump({'name': 'Geopolitical Risk Monitor', 'data_as_of': '2026-10-09', 'research_as_of': '2026-10-11', 'datasets': datasets},
          open(OUT + 'manifest.json', 'w'), ensure_ascii=False, indent=1)

frag = open(os.path.join(SITE, 'dashboard.html')).read()
page = f'''<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Geopolitical Risk Monitor</title>
<meta name="description" content="Cross-asset geopolitical and policy risk monitor: signals, shocks, desks, Fed tracker, catalysts and regulation, with data to 9 Oct 2026.">
<link rel="stylesheet" href="theme.css">
<script src="https://cdnjs.cloudflare.com/ajax/libs/d3/7.9.0/d3.min.js"></script>
<script src="runtime.js"></script>
</head>
<body>
<main class="wrap">
<div id="dash-root">
{frag}
</div>
<footer class="site-foot">Market data to 9 Oct 2026 · research and analyst judgments as of 11 Oct 2026 · research signals, not investment advice ·
<a href="https://github.com/n9omi/geopolitical-risk-monitor">source code and documentation</a></footer>
</main>
</body>
</html>
'''
open(os.path.join(SITE, 'index.html'), 'w').write(page)

# ---- generated docs ----
docs = os.path.join(ROOT, 'docs')
os.makedirs(docs, exist_ok=True)
kb = lambda b: f'{b / 1024:,.0f} KB'
lines = ['# Data inventory', '', '_Generated by `pipeline/07_wrap_site.py` from `site/data/manifest.json`. Do not edit by hand._', '',
         '| Dataset | File | Rows | Dates covered | Size | What it holds |', '|---|---|---:|---|---:|---|']
for d in datasets:
    cov = f"{d['from']} → {d['to']}" if d['from'] else '—'
    lines.append(f"| **{d['title']}** | `{d['file']}` | {d['rows']:,} | {cov} | {kb(d['bytes'])} | {d['description']} |")
open(os.path.join(docs, 'data_inventory.md'), 'w').write('\n'.join(lines) + '\n')

src = {}
for d in datasets:
    rows = json.load(open(OUT + d['file']))
    for r in rows if isinstance(rows, list) else [rows]:
        if isinstance(r, dict):
            u, t = r.get('source_url') or r.get('url'), r.get('source_title') or r.get('title')
            if u and u.startswith('http'):
                src.setdefault(u, {'title': t or u, 'datasets': set()})['datasets'].add(d['id'])
lines = ['# Sources', '', '_Generated by `pipeline/07_wrap_site.py`: every URL cited by a row in the datasets, with the datasets that cite it._', '',
         'Market prices come from Yahoo Finance history pages, FRED, the New York Fed Markets API and the US Treasury par yield curve; see [data inputs](02_data_inputs.md).', '',
         '| Source | Cited in |', '|---|---|']
for u, v in sorted(src.items(), key=lambda kv: kv[1]['title'].lower()):
    lines.append(f"| [{v['title']}]({u}) | {', '.join(sorted(v['datasets']))} |")
open(os.path.join(docs, 'sources.md'), 'w').write('\n'.join(lines) + '\n')
print('datasets', len(datasets), 'sources', len(src), 'page', len(page))
